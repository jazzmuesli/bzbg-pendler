def strip_node_exports(js):
    """Remove Node.js module.exports guards from source JS."""
    return re.sub(
        r'\nif \(typeof module !== "undefined" && module\.exports\) \{\n  module\.exports = .*\n\}\n',
        "\n",
        js,
    )


